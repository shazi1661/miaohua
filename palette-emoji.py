def hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360.0, l / 100.0, s / 100.0)
    return (int(round(r * 255)), int(round(g * 255)), int(round(b * 255)))

def tag(c):
    return "<c=FF%02X%02X%02X>" % c

