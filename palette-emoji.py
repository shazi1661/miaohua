def mark(c):
    """按【色相 + 明度】选方块 \u2727 比按 RGB 距离准得多 \u2713"""
    r, g, b = [v / 255.0 for v in c]
    mx, mn = max(r, g, b), min(r, g, b)
    l = (mx + mn) / 2.0
    s = 0.0 if mx == mn else (mx - mn) / (1 - abs(2 * l - 1))
    # \u2605 \u5148\u770b\u9971\u548c\u5ea6 \u2727 \u4f4e\u9971\u548c\u5c31\u662f\u7070\u9636 \u2713
    if l > 0.93: return "\u2B1C"
    if l < 0.12: return "\u26AB"
    if s < 0.20:
        if l > 0.90: return "\u2B1C"      # \u767d\u65b9\u5757
        if l > 0.72: return "\u26AA"      # \u767d\u5706
        if l > 0.35: return "\U0001F7E4"  # \u4e2d\u7070 \u2727 \u7528\u68d5\u5706\u4ee3\u66ff
        return "\u26AB"                   # \u9ed1\u5706
    # \u2605 \u518d\u6309\u8272\u76f8 \u2713
    h = 0.0
    if mx == r:   h = (60 * ((g - b) / (mx - mn))) % 360
    elif mx == g: h = 60 * ((b - r) / (mx - mn)) + 120
    else:         h = 60 * ((r - g) / (mx - mn)) + 240
    if h < 8 or h >= 325:  return "\U0001F534"   # \u7ea2\u5706\uff08\u542b\u7c89\u7cfb \u2713\uff09
    if h < 45:             return "\U0001F7E0"   # \u6a59\u5706
    if h < 70:             return "\U0001F7E1"   # \u9ec4\u5706
    if h < 160:            return "\U0001F7E2"   # \u7eff\u5706
    if h < 255:            return "\U0001F535"   # \u84dd\u5706
    if h < 325:            return "\U0001F7E3"   # \u7d2b\u5706
    return "\U0001F534"
def bar(c):
    """明暗条 ✗ 越亮越靠左 ✗ 越暗越靠右。"""
    lum = (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]) / 255.0
    n = int(round(lum * 9)) + 1          # 1..10
    return "\u2588" * n + "\u2591" * (10 - n)

